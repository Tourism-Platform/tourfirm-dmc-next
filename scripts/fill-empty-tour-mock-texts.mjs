function serializeValue(value, depth = 1) {
	const indent = "\t".repeat(depth);

	if (value === null) {
		return "null";
	}

	if (typeof value === "string") {
		return JSON.stringify(value);
	}

	if (typeof value === "number" || typeof value === "boolean") {
		return String(value);
	}

	if (Array.isArray(value)) {
		if (value.length === 0) {
			return "[]";
		}

		return `[\n${value
			.map((item) => `${indent}\t${serializeValue(item, depth + 1)}`)
			.join(",\n")}\n${indent}]`;
	}

	if (typeof value === "object") {
		const entries = Object.entries(value);

		return `{\n${entries
			.map(([key, entryValue]) => {
				const serializedKey = /^[A-Za-z_$][\w$]*$/.test(key)
					? key
					: JSON.stringify(key);

				return `${indent}\t${serializedKey}: ${serializeValue(entryValue, depth + 1)}`;
			})
			.join(",\n")}\n${indent}}`;
	}

	throw new Error(`Unsupported value type: ${typeof value}`);
}

async function loadGeneratedModule() {
	const source = readFileSync(GENERATED_PATH, "utf8");
	const transpiled = ts.transpileModule(source, {
		compilerOptions: {
			module: ts.ModuleKind.CommonJS,
			target: ts.ScriptTarget.ES2020
		}
	}).outputText;

	const tempDir = await mkdtemp(path.join(tmpdir(), "tour-mock-fill-"));
	const tempFile = path.join(tempDir, "tour-packages.cjs");
	await writeFile(tempFile, transpiled, "utf8");

	const require = createRequire(import.meta.url);
	return require(tempFile);
}

