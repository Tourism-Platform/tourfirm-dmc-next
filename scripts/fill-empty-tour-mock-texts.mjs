function detectLanguage(text) {
	if (!text) return "en";
	if (/[\u3040-\u30ff\u4e00-\u9faf]/.test(text)) return "ja";
	if (/[\u0400-\u04ff]/.test(text)) return "ru";
	if (/[äöüß]|Taschkent|Bischkek|Usbekistan|Reise|Übernachtung/i.test(text)) return "de";
	if (/[àâçéèêëïîôùûü]|voyage|découvrir|Ouzbékistan/i.test(text)) return "fr";
	if (/[áéíóúñ¿¡]|viaje|descubrir|Uzbekistán/i.test(text)) return "es";
	return "en";
}

