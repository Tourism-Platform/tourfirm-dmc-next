function capitalizeCity(city) {
	if (!city) return "";
	return city.charAt(0).toUpperCase() + city.slice(1);
}

function getEventCity(event) {
	const loc =
		event.details?.location ??
		event.details?.hop?.[0]?.arrival?.location ??
		event.details?.hop?.[0]?.departure?.location;
	return capitalizeCity(loc?.city ?? "");
}

function firstSentence(text, maxLen = 80) {
	const cleaned = text.replace(/\s+/g, " ").trim();
	if (!cleaned) return "";
	const match = cleaned.match(/^[^.!?\n]+[.!?]?/);
	const sentence = (match?.[0] ?? cleaned).trim();
	return sentence.length > maxLen ? `${sentence.slice(0, maxLen - 1)}…` : sentence;
}

function inferEventName(event, lang, labels) {
	const city = getEventCity(event);
	const name = event.name?.trim() ?? "";
	const description = event.description?.trim() ?? "";

	if (name) return name;

	if (description) {
		return firstSentence(description, 60) || labels.dayProgram(event.day);
	}

	switch (event.typ) {
		case "5":
			return city ? labels.hotelIn(city) : "Hotel";
		case "2": {
			const hop = event.details?.hop?.[0];
			const from = capitalizeCity(hop?.departure?.location?.city ?? "");
			const to = capitalizeCity(hop?.arrival?.location?.city ?? "");
			if (from && to) return `${from} - ${to}`;
			return city ? labels.transport(from || city, to || city) : "Transfer";
		}
		case "6":
			return city ? `Sightseeing in ${city}` : "Sightseeing";
		case "7":
		default:
			return labels.dayProgram(event.day);
	}
}

function inferEventDescription(event, lang, labels) {
	const city = getEventCity(event);
	const name = event.name?.trim() ?? "";
	const description = event.description?.trim() ?? "";

	if (description) return description;

	const lowerName = name.toLowerCase();

	if (event.typ === "5") {
		if (city) return labels.accommodation(city);
		return labels.accommodation("the hotel");
	}

	if (event.typ === "2") {
		const hop = event.details?.hop?.[0];
		const from = capitalizeCity(hop?.departure?.location?.city ?? city);
		const to = capitalizeCity(hop?.arrival?.location?.city ?? city);
		if (from && to) return labels.transport(from, to);
		if (name) return labels.transfer(name);
		return labels.program;
	}

	if (event.typ === "6") {
		if (/museum/i.test(name)) return labels.museum(city || "the city");
		return labels.sightseeing(name || "Sightseeing", city || "the city");
	}

	if (/check.?in|check.?out/i.test(lowerName)) {
		return labels.checkInOut;
	}

	if (/museum/i.test(lowerName)) {
		return labels.museum(city || "the city");
	}

	if (/program/i.test(lowerName)) {
		return labels.program;
	}

	if (/arrival|ankunft|anreise|arriv/i.test(lowerName)) {
		return labels.arrival(city || name.replace(/arrival|ankunft|anreise|arriv/i, "").trim() || "the city");
	}

	if (/full day|ganztäg|journée complète|día completo/i.test(lowerName) && city) {
		return labels.fullDay(city);
	}

	if (name.includes(" - ") || name.includes(" – ") || /by (car|train|bus|flight)/i.test(name)) {
		return labels.transfer(name);
	}

	if (name) {
		return `${name}. ${labels.program}`;
	}

	return labels.dayProgram(event.day);
}

function inferTourTitle(bundle, lang, labels) {
	const candidates = [
		bundle.catalog?.title,
		bundle.general?.name,
		bundle.landing?.title,
		bundle.options?.[0]?.name
	].filter((v) => v?.trim());

	if (candidates.length > 0) return candidates[0].trim();

	const events = bundle.optionDetail?.events ?? [];
	const namedEvents = events
		.map((e) => e.name?.trim())
		.filter(Boolean);

	if (namedEvents.length > 0) {
		const cities = [...new Set(events.map(getEventCity).filter(Boolean))];
		if (cities.length >= 2) {
			return `${labels.defaultTitle}: ${cities.slice(0, 4).join(" – ")}`;
		}
	}

	return labels.defaultTitle;
}

function inferTourDescription(bundle, title, labels) {
	const events = bundle.optionDetail?.events ?? [];
	const snippets = events
		.map((e) => e.description?.trim())
		.filter((d) => d && d.length > 20)
		.slice(0, 2);

	if (snippets.length > 0) {
		return snippets.join("\n\n");
	}

	return labels.tourDesc(title);
}

function fillBundle(bundle) {
	const langSource =
		bundle.catalog?.title ||
		bundle.general?.name ||
		bundle.landing?.title ||
		bundle.optionDetail?.events?.find((e) => e.name || e.description)?.name ||
		bundle.optionDetail?.events?.find((e) => e.description)?.description ||
		"";
	const lang = detectLanguage(langSource);
	const labels = LABELS[lang];

	const title = inferTourTitle(bundle, lang, labels);

	if (!bundle.catalog.title?.trim()) bundle.catalog.title = title;
	if (!bundle.general.name?.trim()) bundle.general.name = title;
	if (!bundle.landing.title?.trim()) bundle.landing.title = title;

	if (!bundle.catalog.description?.trim()) {
		bundle.catalog.description = inferTourDescription(bundle, title, labels);
	}

	for (const option of bundle.options ?? []) {
		if (!option.name?.trim()) option.name = title;
		if (option.description === "") {
			option.description = bundle.catalog.description;
		}
	}

	const events = bundle.optionDetail?.events ?? [];
	for (const event of events) {
		event.name = inferEventName(event, lang, labels);
		event.description = inferEventDescription(event, lang, labels);
	}

	return bundle;
}

function syncCatalogTour(catalogTour, bundle) {
	if (!catalogTour.title?.trim()) catalogTour.title = bundle.catalog.title;
	if (!catalogTour.description?.trim()) {
		catalogTour.description = bundle.catalog.description;
	}
}

function countEmptyStrings(obj, path = "") {
	let count = 0;
	if (typeof obj === "string" && obj === "") {
		return 1;
	}
	if (Array.isArray(obj)) {
		for (const item of obj) count += countEmptyStrings(item);
	} else if (obj && typeof obj === "object") {
		for (const value of Object.values(obj)) count += countEmptyStrings(value);
	}
	return count;
}

async function main() {
	const module = await loadGeneratedModule();
	const tourPackageMocks = structuredClone(module.TOUR_PACKAGE_MOCKS);

	for (const bundle of Object.values(tourPackageMocks)) {
		fillBundle(bundle);
	}

	const catalogToursMock = structuredClone(module.CATALOG_TOURS_MOCK);
	const popularToursMock = structuredClone(module.POPULAR_TOURS_MOCK);
	const specialOffersMock = structuredClone(module.SPECIAL_OFFERS_MOCK);

	const bundleById = tourPackageMocks;

	for (const list of [catalogToursMock, popularToursMock, specialOffersMock]) {
		for (const tour of list) {
			const bundle = bundleById[tour.id];
			if (bundle) syncCatalogTour(tour, bundle);
		}
	}

	const before = countEmptyStrings(module.TOUR_PACKAGE_MOCKS);
	const after = countEmptyStrings(tourPackageMocks);

	const output = buildGeneratedFile({
		tourPackageMocks,
		catalogToursMock,
		popularToursMock,
		specialOffersMock,
		catalogRegionsMock: structuredClone(module.CATALOG_REGIONS_MOCK),
		priceHistogramMock: structuredClone(module.PRICE_HISTOGRAM_MOCK),
		defaultTourPackageId: module.DEFAULT_TOUR_PACKAGE_ID
	});

	writeFileSync(GENERATED_PATH, output, "utf8");

	console.log(`Filled empty texts: ${before} → ${after} empty strings remaining.`);
	console.log(`Written to ${GENERATED_PATH}`);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
