import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { mkdir, mkdtemp, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const GENERATED_PATH = path.join(
	ROOT,
	"src/entities/tour/catalog/mock/generated/tour-packages.generated.ts"
);
const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const EXCLUDED_IMAGE_PATHS = new Set([
	"/assets/images/destinations/route-map-overlay.png"
]);
const COVER_POOL_DIRS = [
	"images/city",
	"images/destinations",
	"images/service-areas",
	"images/tours"
].map((segment) => path.join(ROOT, "public/assets", segment));

function collectAssetImages(dir, base) {
	const entries = readdirSync(dir, { withFileTypes: true });
	const images = [];

	for (const entry of entries) {
		if (!entry.isFile()) continue;

		const urlPath = `${base}/${entry.name}`;
		const ext = path.extname(entry.name).toLowerCase();

		if (IMAGE_EXTENSIONS.has(ext) && !EXCLUDED_IMAGE_PATHS.has(urlPath)) {
			images.push(urlPath);
		}
	}

	return images;
}

const COVER_POOL = COVER_POOL_DIRS.flatMap((dir) => {
	const base = `/assets/${path.relative(path.join(ROOT, "public/assets"), dir).replace(/\\/g, "/")}`;
	return collectAssetImages(dir, base);
}).sort();

function hashTourId(id) {
	return [...id].reduce((sum, char) => sum + char.charCodeAt(0), 0);
}

function pickImage(tourId, offset = 0) {
	return COVER_POOL[(hashTourId(tourId) + offset) % COVER_POOL.length];
}

function applyBundleImages(tourId, bundle) {
	const cover = pickImage(tourId, 0);

	bundle.catalog.image_url = cover;
	bundle.general.cover_image_path = cover;

	if (Array.isArray(bundle.landing.images) && bundle.landing.images.length > 0) {
		bundle.landing.images = bundle.landing.images.map((image, index) => ({
			...image,
			image_url: pickImage(tourId, index + 1),
			is_primary: index === 0
		}));
	}

	return bundle;
}

function applyListImages(tours) {
	return tours.map((tour) => ({
		...tour,
		image_url: pickImage(tour.id, 0)
	}));
}

function serializeValue(value, depth = 1) {
	const indent = "\t".repeat(depth);

	if (value === null) {
		return "null";
	}

	if (typeof value === "string") {
		return JSON.stringify(value);
	}

	if (typeof value === "number" || typeof value === "boolean") {
		return String(value);
	}

	if (Array.isArray(value)) {
		if (value.length === 0) {
			return "[]";
		}

		return `[\n${value
			.map((item) => `${indent}\t${serializeValue(item, depth + 1)}`)
			.join(",\n")}\n${indent}]`;
	}

	if (typeof value === "object") {
		const entries = Object.entries(value);

		return `{\n${entries
			.map(([key, entryValue]) => {
				const serializedKey = /^[A-Za-z_$][\w$]*$/.test(key)
					? key
					: JSON.stringify(key);

				return `${indent}\t${serializedKey}: ${serializeValue(entryValue, depth + 1)}`;
			})
			.join(",\n")}\n${indent}}`;
	}

	throw new Error(`Unsupported value type: ${typeof value}`);
}

async function loadGeneratedModule() {
	const source = readFileSync(GENERATED_PATH, "utf8");
	const transpiled = ts.transpileModule(source, {
		compilerOptions: {
			module: ts.ModuleKind.CommonJS,
			target: ts.ScriptTarget.ES2020
		}
	}).outputText;

	const tempDir = await mkdtemp(path.join(tmpdir(), "tour-mock-"));
	const tempFile = path.join(tempDir, "tour-packages.cjs");
	await writeFile(tempFile, transpiled, "utf8");

	const require = createRequire(import.meta.url);
	return require(tempFile);
}

function buildGeneratedFile({
	tourPackageMocks,
	catalogToursMock,
	popularToursMock,
	specialOffersMock,
	catalogRegionsMock,
	priceHistogramMock,
	defaultTourPackageId
}) {
	return `/* eslint-disable */
// generated by scripts/build-tour-packages-mock.mjs — do not edit manually
import type { ICatalogTourBackend } from "../../types";

import type { ITourPackageMockBundle } from "./tour-packages.types";

export type { ITourPackageMockBundle } from "./tour-packages.types";

export const DEFAULT_TOUR_PACKAGE_ID = ${JSON.stringify(defaultTourPackageId)};

export const TOUR_PACKAGE_MOCKS: Record<string, ITourPackageMockBundle> = ${serializeValue(
		tourPackageMocks,
		0
	)};

export const CATALOG_TOURS_MOCK: ICatalogTourBackend[] = ${serializeValue(
		catalogToursMock,
		0
	)};

export const POPULAR_TOURS_MOCK: ICatalogTourBackend[] = ${serializeValue(
		popularToursMock,
		0
	)};

export const SPECIAL_OFFERS_MOCK: ICatalogTourBackend[] = ${serializeValue(
		specialOffersMock,
		0
	)};

export const CATALOG_REGIONS_MOCK = ${serializeValue(catalogRegionsMock, 0)};

export const PRICE_HISTOGRAM_MOCK = ${serializeValue(priceHistogramMock, 0)};
`;
}

async function main() {
	const module = await loadGeneratedModule();

	const sourceTourPackages =
		module.TOUR_PACKAGE_MOCKS_BY_LOCALE?.en ?? module.TOUR_PACKAGE_MOCKS;
	const sourceCatalogTours =
		module.CATALOG_TOURS_MOCK_BY_LOCALE?.en ?? module.CATALOG_TOURS_MOCK;
	const sourcePopularTours =
		module.POPULAR_TOURS_MOCK_BY_LOCALE?.en ?? module.POPULAR_TOURS_MOCK;
	const sourceSpecialOffers =
		module.SPECIAL_OFFERS_MOCK_BY_LOCALE?.en ?? module.SPECIAL_OFFERS_MOCK;
	const sourceCatalogRegions =
		module.CATALOG_REGIONS_MOCK_BY_LOCALE?.en ?? module.CATALOG_REGIONS_MOCK;
	const sourcePriceHistogram =
		module.PRICE_HISTOGRAM_MOCK_BY_LOCALE?.en ?? module.PRICE_HISTOGRAM_MOCK;

	const tourPackageMocks = Object.fromEntries(
		Object.entries(sourceTourPackages).map(([tourId, bundle]) => [
			tourId,
			applyBundleImages(tourId, structuredClone(bundle))
		])
	);

	const catalogToursMock = applyListImages(structuredClone(sourceCatalogTours));
	const popularToursMock = applyListImages(structuredClone(sourcePopularTours));
	const specialOffersMock = applyListImages(
		structuredClone(sourceSpecialOffers)
	);
	const catalogRegionsMock = structuredClone(sourceCatalogRegions);
	const priceHistogramMock = structuredClone(sourcePriceHistogram);

	const output = buildGeneratedFile({
		tourPackageMocks,
		catalogToursMock,
		popularToursMock,
		specialOffersMock,
		catalogRegionsMock,
		priceHistogramMock,
		defaultTourPackageId: module.DEFAULT_TOUR_PACKAGE_ID
	});

	await mkdir(path.dirname(GENERATED_PATH), { recursive: true });
	writeFileSync(GENERATED_PATH, output, "utf8");

	console.log(
		`Done. ${Object.keys(tourPackageMocks).length} tours, ${COVER_POOL.length} cover images.`
	);
	console.log(`Written to ${GENERATED_PATH}`);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
